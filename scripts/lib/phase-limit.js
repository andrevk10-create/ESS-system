module.exports=function applyPhaseLimit(flows){
    for(const n of flows){
        if(n.type==='function'&&n.func) n.func=n.func.replaceAll('|| 25) - 3','|| 25) - 1').replaceAll('||25)-3','||25)-1').replace('existingEvCurrent + 22 - power / voltage', "existingEvCurrent + Math.max(0,(Number(essRuntimeConfig.specs?.mainFuseA)||25)-1) - power / voltage");
        if(n.type==='ui-template'&&n.format)n.format=n.format.replaceAll('Veilige ontwerpgrens 22 A','Veilige ontwerpgrens 24 A');
    }
};
