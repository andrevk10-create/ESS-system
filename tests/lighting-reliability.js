const assert=require('node:assert/strict');
const flows=require('../flows.json');
const control=new Function('global','flow','node','msg',flows.find(n=>n.id==='esslights_ctrl01').func);
const retry=new Function('global','flow','node','msg',flows.find(n=>n.id==='esslights_retry_check').func);
const data={ess_system_config:{modules:{lighting:true},entities:{'light.zone_1':'light.test'}}};
const flow={get:k=>data[k],set:(k,v)=>data[k]=v};
const states={'light.test':{state:'off',attributes:{brightness:0}}};
const global={get:()=>({homeAssistant:{states}})},node={warn:()=>{},status:()=>{}};
const on={topic:'ess/light/toggle',payload:{key:'zone-1',active:true,requestId:'first'}};
data.ess_system_config.entities['light.zone_3']='light.office';
states['light.office']={state:'off',attributes:{brightness:0}};
const office=control(global,flow,node,{topic:'ess/light/toggle',payload:{key:'zone-1',role:'light.zone_3',active:true,requestId:'office'}});
assert.deepStrictEqual(office[0].payload.target.entity_id,['light.office'],'The displayed canonical role must win over an obsolete room key');
assert.equal(data.ess_light_commands['light.test'],undefined,'Office control must not affect the utility room');
assert.equal(control(global,flow,node,{topic:'ess/light/toggle',payload:{key:'zone-1',role:'light.unconfigured',active:true}}),null,'Reject an unconfigured role even if its key is allowed');
const first=control(global,flow,node,on);
assert(first[0] && first[2]);
assert.equal(control(global,flow,node,on),null,'Duplicate browser delivery must not restart the command');
const repeated=retry(global,flow,node,first[2]);
assert.equal(repeated[0].payload.data.entity_id[0],'light.test');
assert.equal(repeated[1],null,'An unconfirmed ON must never become a toggle');
states['light.test']={state:'on',attributes:{brightness:255}};
assert.equal(retry(global,flow,node,repeated[2]),null,'Stop once the real light confirms');
assert.equal(data.ess_light_commands['light.test'].status,'confirmed');
const off=control(global,flow,node,{topic:'ess/light/toggle',payload:{key:'zone-1',active:false,requestId:'second'}});
const newer=control(global,flow,node,{...on,payload:{...on.payload,requestId:'third'}});
assert.equal(retry(global,flow,node,off[2]),null,'A newer intent supersedes delayed OFF retries');
states['light.test'].state='off';
retry(global,flow,node,newer[2]);retry(global,flow,node,newer[2]);
assert.equal(retry(global,flow,node,newer[2]),null,'Attempts are bounded');
assert.equal(data.ess_light_commands['light.test'].status,'failed');
const changed=control(global,flow,node,{...on,payload:{...on.payload,requestId:'fourth'}});
data.ess_system_config.entities['light.zone_1']='light.other';
assert.equal(retry(global,flow,node,changed[2]),null,'A remapping cancels pending commands');
const component=new Function(flows.find(n=>n.id==='esstpl_lights001').format.match(/<script>([\s\S]*?)<\/script>/)[1].replace('export default','return'))();
const vm=require('node:vm');const timers=[];const sent=[];
const sendIntent=vm.runInNewContext('('+component.methods.sendLightIntent.toString().replace(/^sendLightIntent/, 'function')+')',{setTimeout:fn=>timers.push(fn)});
const ui={pendingLights:{room:{token:1}},send:m=>sent.push(m)};
sendIntent.call(ui,{key:'room'},'ess/light/toggle',{key:'room',active:true});
timers.shift()();assert.equal(sent.length,2);assert.equal(sent[0].payload.requestId,sent[1].payload.requestId);
sendIntent.call(ui,{key:'room'},'ess/light/toggle',{key:'room',active:false});
ui.pendingLights.room={token:2};timers.shift()();assert.equal(sent.length,3,'A delayed browser resend cannot replace newer intent');
console.log('Lighting: dropped delivery, fixed-intent retry, confirmation, supersession, retry limits and remapping passed');
