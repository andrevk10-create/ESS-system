const assert=require('node:assert/strict');
const {witHealthModel}=require('../scripts/lib/wit-dashboard');
const {dashboardHealth,dashboardAlerts}=require('../scripts/lib/dashboard-diagnostics');
const flows=require('../flows.json'),get=id=>flows.find(n=>n.id===id);
let now=Date.parse('2026-10-24T15:00:00Z');
class Clock extends Date{constructor(...args){super(...(args.length?args:[now]))}static now(){return now}}
const reading=(value,at=now)=>({state:String(value),attributes:{unit_of_measurement:'W'},last_reported:new Date(at).toISOString(),last_updated:new Date(at-3600000).toISOString()});
const states={'sensor.p1_meter_vermogen':reading(0),'sensor.growatt_battery_battery_power':reading(0),'sensor.growatt_battery_battery_soc':reading(70)};
const values={ess_wit_grid_charge_status:{updatedAt:new Date(now).toISOString(),status:'P1-meetdata ontbreekt of is te oud'},ess_wit_audi_discharge_status:{updatedAt:new Date(now).toISOString()},ess_system_config:{entities:{},modules:{energy:true,battery:true,ev:false,nas:false,climate:false}}};
const flow={get:k=>values[k],set:(k,v)=>values[k]=v};
let model=witHealthModel(states,flow,now);
assert.equal(model.p1Fresh,true,'An unchanged but newly reported value is fresh');
now+=20000;
model=witHealthModel(states,flow,now);
assert.equal(model.p1Fresh,false,'Strict freshness is not relaxed for control consumers');
assert.equal(model.p1Warning,false,'Brief delay is not promoted to a repeating warning');
assert.equal(model.measurementPending,true);
assert.equal(model.level,'ok');
const d={grid:{power:0},solar:{power:0},battery:{soc:70},wit:{runtime:model},alarms:[]};
assert.equal(dashboardHealth(d,{climate:false,nas:false,ev:false},false,'')[0].level,'ok');
now+=26000;model=witHealthModel(states,flow,now);
assert.equal(model.p1Warning,true,'Persistent >45 s P1 delay remains actionable');
assert.equal(model.level,'error');
const persistent={...d,wit:{runtime:model},alarms:[{level:'error',text:'P1-meetdata ontbreekt of is te oud'}]};
assert.equal(dashboardAlerts(persistent,dashboardHealth(persistent,{climate:false,nas:false,ev:false},false,''),{}).filter(a=>a.text.includes('P1')).length,1,'One P1 outage is not repeated as three separate alarms');
states['sensor.p1_meter_vermogen']=reading(0);
assert.equal(witHealthModel(states,flow,now).p1Warning,false,'Real fresh report clears the warning');
states['sensor.p1_meter_vermogen']=reading('unavailable');
assert.equal(witHealthModel(states,flow,now).p1Warning,true,'Explicit unavailability stays visible immediately');
states['sensor.p1_meter_vermogen']=reading(0);
states['sensor.growatt_battery_battery_power']=reading(0,now-125000);
model=witHealthModel(states,flow,now);
assert.equal(model.telemetryFresh,false);assert.equal(model.telemetryWarning,false);
assert.equal(model.measuredPowerW,null,'Display grace does not fabricate a measured power');
states['sensor.growatt_battery_battery_power']=reading(0,now-151000);
assert.equal(witHealthModel(states,flow,now).telemetryWarning,true);
values.ess_wit_command_fault={reason:'Hard fault'};
assert.match(witHealthModel(states,flow,now).status,/geblokkeerd/,'Hardware faults are never delayed');
delete values.ess_wit_command_fault;
states['sensor.growatt_battery_battery_power']=reading(0);
const before=JSON.stringify(states);
new Function('global','flow','node','msg','Date',get('ess00000000000a').func)({get:()=>({homeAssistant:{states,isConnected:true}})},flow,{status(){},warn(){}},{},Clock);
const dashboard=values.ess_dashboard_live;
assert.equal(dashboard.updatedAt,new Date(now).toISOString(),'Dashboard heartbeat is independent of last P1 value change');
assert.equal(dashboard.sourceTimestamps.p1,states['sensor.p1_meter_vermogen'].last_reported);
assert.equal(JSON.stringify(states),before,'Heartbeat never refreshes sensor timestamps');
assert.equal(dashboard.connection.homeAssistant,true);
const offline={...d,connection:{homeAssistant:false}};
assert.match(dashboardHealth(offline,{climate:false,nas:false,ev:false},false,'')[0].detail,/Home Assistant onderbroken/);
assert.equal(dashboardHealth(d,{},true,'')[0].level,'error','A missing dashboard heartbeat remains an error');
assert(dashboardAlerts(d,dashboardHealth(d,{},true,''),{}).some(a=>a.text.includes('Geen actuele update')));
const component=new Function(get('esstpl_system001').format.match(/<script[^>]*>([\s\S]*?)<\/script>/)[1].replace('export default','return'))();
assert.equal(component.computed.stale.call({d:dashboard,pageNow:now+31000}),true,'Browser clock detects stopped dashboard updates');
console.log('Dashboard freshness: independent heartbeat, unchanged reports, short-delay grace, persistent outage, offline connection and immediate fault visibility passed');
