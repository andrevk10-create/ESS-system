const assert=require('node:assert/strict');
const {analyticsDayBounds:bounds,analyticsReplay:replay,analyticsRecoveryRequest:request,analyticsRecoveryApply:apply}=require('../scripts/lib/analytics-recovery');
const {costLedgerStep}=require('../scripts/lib/energy-costs');
const start=Date.parse('2026-10-20T22:00:00Z'),end=start+86400000,day='2026-10-21';
const mapped=Object.fromEntries(['sensor.p1_meter_vermogen','sensor.growatt_solar_system_output_power','sensor.ev_charger_power','sensor.ev_charger_status','sensor.ev_charger_2_power','sensor.ev_charger_2_status','sun.sun'].map(r=>[r,r]));
const row=(id,state,unit,at=start)=>({entity_id:id,state:String(state),attributes:{unit_of_measurement:unit},last_updated:new Date(at).toISOString()});
const rows=[row('sensor.p1_meter_vermogen',4000,'W'),row('sensor.growatt_solar_system_output_power',0,'W'),row('sensor.ev_charger_power',2,'kW'),row('sensor.ev_charger_status','charging'),row('sensor.ev_charger_2_power',0,'W'),row('sensor.ev_charger_2_status','disconnected'),row('sun.sun','below_horizon')];
const prices=[{start,end,price:.3}];
const r=replay(rows,mapped,start,end,prices);
assert.equal(r.seconds,86400);assert.equal(r.kwh,48);assert.equal(r.cars.audi.kwh,48);assert(Math.abs(r.cars.audi.cost-14.4)<1e-9);
assert.equal(r.cars.jeep.kwh,0);
const gapRows=[...rows,row('sensor.ev_charger_power','unavailable','W',start+3600000),row('sensor.ev_charger_power',2,'kW',start+7200000)];
const gap=replay(gapRows,mapped,start,end,prices);
assert.equal(gap.seconds,23*3600,'Explicit unavailable breaks learning coverage');assert.equal(gap.cars.audi.seconds,23*3600);
assert.equal(replay(rows,mapped,start,end,[]).cars.audi.unpriced,48,'Missing tariffs are never zero-priced');
const mismatch=replay([...rows,row('sensor.ev_charger_status','paused')],mapped,start,end,prices);
assert.equal(mismatch.seconds,0,'Contradictory status and power cannot teach household demand');
const solarOnly=replay([...rows,row('sensor.p1_meter_vermogen',0,'W'),row('sensor.growatt_solar_system_output_power',4000,'W')],mapped,start,end,[]);
assert.equal(solarOnly.cars.audi.unpriced,0,'No grid purchase needs no purchase tariff');
assert.equal(solarOnly.cars.audi.cost,0);
assert.equal(bounds(Date.parse('2026-10-25T12:00:00Z')).end-bounds(Date.parse('2026-10-25T12:00:00Z')).start,25*3600000);
assert.equal(bounds(Date.parse('2026-03-29T12:00:00Z')).end-bounds(Date.parse('2026-03-29T12:00:00Z')).start,23*3600000);
const sample={binding:'x',grid:4000,house:4000,battery:0,audi:{binding:'a',connected:true,power:2000},jeep:{binding:'j',connected:false,power:0}};
let ledger=costLedgerStep(null,sample,[],start);ledger=costLedgerStep(ledger,sample,[],start+60000);
ledger.priceArchive=prices;
const values={ess_charging_preferences_ready:true,ess_system_config:{entities:mapped},ess_energy_cost_ledger:ledger,ess_house_time_profile:{version:1,days:{}},ess_house_consumption_learning:{schemaVersion:2,recentDays:[],currentDate:'2026-10-22'}};
const flow={get:k=>values[k],set:(k,v)=>values[k]=v};
const now=end+3600000;
let msg=request(flow,now);assert(msg);assert.equal(request(flow,now),null,'One in-flight history request');
assert.equal(msg.analyticsRequest.key,day);msg.payload=[rows];apply(flow,msg,now);
assert.equal(values.ess_house_consumption_learning.recentDays[0].kwh,48);
assert.equal(ledger.days[day].audiKwh,48);assert(Math.abs(ledger.total.audiCost-14.4)<1e-9);
assert.equal(ledger.total.audiUnpricedKwh,0);
const before=JSON.stringify(ledger.total);values.ess_analytics_pending=msg.analyticsRequest;apply(flow,msg,now);
assert.equal(JSON.stringify(ledger.total),before,'Repeated recovery cannot double book');
assert.equal(request(flow,now+300000).analyticsRequest.key,'2026-10-22','Alternate catch-up with current-day recovery');
values.ess_analytics_pending=null;
assert.equal(request(flow,now+600000).analyticsRequest.key,'2026-10-20','Catch up older days instead of rereading yesterday');
const invalid={...msg,analyticsRequest:{...msg.analyticsRequest,at:now+1}};assert.equal(apply(flow,invalid,now),null);
// Stored tariffs remain available after the planner drops elapsed quarters.
let archived=costLedgerStep(null,sample,[{start:new Date(start).toISOString(),end:new Date(end).toISOString(),allInPrice:.3}],start);
archived=costLedgerStep(archived,sample,[],start+60000);assert(archived.total.audiCost>0);
// Reconcile a current-day prefix while preserving the live tail.
const partialEnd=start+3600000;
ledger=costLedgerStep(null,sample,[],start);ledger=costLedgerStep(ledger,sample,[],start+60000);
ledger.priceArchive=prices;values.ess_energy_cost_ledger=ledger;
const partial={key:day,start,end:partialEnd,mapped,binding:JSON.stringify(mapped),at:now};
values.ess_analytics_pending=partial;apply(flow,{analyticsRequest:partial,payload:[rows]},now);
assert.equal(ledger.days[day].audiKwh,2);
const partialTotal=JSON.stringify(ledger.total);
values.ess_analytics_pending=partial;apply(flow,{analyticsRequest:partial,payload:[rows]},now);
assert.equal(JSON.stringify(ledger.total),partialTotal,'Partial-day recovery is idempotent too');
// One bad quarter does not prevent other quarters from being repaired.
ledger=costLedgerStep(null,sample,[],start);ledger=costLedgerStep(ledger,sample,[],start+60000);
ledger.priceArchive=prices;values.ess_energy_cost_ledger=ledger;
const withGap={...partial,end:start+3*3600000};values.ess_analytics_pending=withGap;
apply(flow,{analyticsRequest:withGap,payload:[gapRows]},now);
assert.equal(ledger.days[day].audiKwh,4,'Recover good hours around an explicit unavailable hour');
// A whole missing day after an ESS outage must also be reconstructible.
ledger=costLedgerStep(null,sample,[],start-86400000);ledger.priceArchive=prices;values.ess_energy_cost_ledger=ledger;
assert.equal(ledger.days[day],undefined);
values.ess_analytics_pending=partial;apply(flow,{analyticsRequest:partial,payload:[rows]},now);
assert.equal(ledger.days[day].audiKwh,2);
values.ess_analytics_pending=partial;values.ess_system_config.entities={...mapped,'sensor.ev_charger_power':'sensor.other'};
assert.equal(apply(flow,{analyticsRequest:partial,payload:[rows]},now),null,'Reject replies after remapping');
console.log('Analytics recovery: missing reports, explicit gaps, costs, no double booking, bounded catch-up, tariff archive and DST passed');
