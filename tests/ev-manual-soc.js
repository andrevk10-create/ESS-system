const assert=require('node:assert/strict');
const {manualCarSoc}=require('../scripts/lib/ev-manual-soc');
const now=Date.parse('2026-10-12T18:00:00Z'),anchor='sensor.car_soc';
assert.equal(manualCarSoc(null,anchor,null,NaN,now).soc,null);
const manual={soc:75,anchor,at:now};
assert.equal(manualCarSoc(manual,anchor,99,now-1000,now).soc,75,'A stale cached vehicle value cannot discard the explicit input');
assert.equal(manualCarSoc(manual,anchor,null,NaN,now+86400000).soc,75,'Explicit input remains until a new real report');
assert.equal(manualCarSoc(manual,anchor,99,now+1000,now+2000).clear,true,'Online vehicle report replaces explicit input');
assert.equal(manualCarSoc(manual,'sensor.other_soc',null,NaN,now).soc,null,'Remapping never transfers manual input');
const f=require('../flows.json'),values={ess_system_config:{entities:{'sensor.ev_state_of_charge':anchor}}};
const flow={get:k=>values[k],set:(k,v)=>values[k]=v},global={get:()=>({homeAssistant:{states:{}}})};
const run=new Function('msg','flow','global',f.find(n=>n.id==='essmanualsoc_set').func);
assert.equal(run({topic:'ess/audi/explicit-soc',payload:''},flow,global),null);
run({topic:'ess/audi/explicit-soc',payload:0},flow,global);
assert.equal(values.ess_audi_explicit_soc.soc,0);
assert.equal(values.ess_jeep_explicit_soc,undefined,'Audi and Jeep inputs are independent');
run({topic:'ess/audi/explicit-soc',payload:null},flow,global);
assert.equal(values.ess_audi_explicit_soc,null);
console.log('Explicit SOC: user opt-in, stale cache rejection, online handover, clearing and vehicle isolation OK');
