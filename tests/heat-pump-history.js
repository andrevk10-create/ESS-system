const assert=require('node:assert/strict');
const {heatPumpHistoryStep:step,heatPumpSettings}=require('../scripts/lib/heat-pump-history');
const base=Date.parse('2026-10-18T20:00:00+02:00');
let v;
const sample=(s,w,binding='sensor.test_heat_pump')=>{const at=base+s*1000;v=step(v,{w,at,binding},at);return v;};
sample(0,70);sample(30,70);
assert.equal(v.running,false);
sample(60,1000);assert.equal(v.running,false,'A short spike does not start a run');
sample(90,1000);assert.equal(v.running,true);
assert.equal(v.total.starts,1);
sample(120,1000);assert.equal(v.total.seconds,30);
sample(150,4000);sample(180,4000);assert.equal(v.total.highSeconds,30);
const saved=v.total.seconds;
v=step(v,{w:4000,at:base+180000,binding:'sensor.test_heat_pump'},base+190000);
assert.equal(v.total.seconds,saved,'Repeated cached readings cannot add runtime');
v=step(v,null,base+400000);
assert.equal(v.running,null);assert(v.total.unknownSeconds>=220);
sample(410,4000);sample(440,4000);
assert.equal(v.total.starts,1,'A reconnect into an active run is not a measured start');
sample(470,70);sample(500,70);assert.equal(v.running,false);
assert.equal(v.total.stops,1,'Only a confirmed running-to-off transition counts as a stop');
sample(530,4000);sample(560,4000);assert.equal(v.total.starts,2);
const total=v.total.seconds;
sample(590,4000,'sensor.replacement');assert.equal(v.total.seconds,total,'Changing meter binding cannot join readings');
assert.equal(v.total.stops,1,'Missing data, reconnects and remapping never invent stops');
assert(heatPumpSettings({offW:500,onW:300}).onW>500);
assert.throws(()=>step({version:1},null,base),/ongeldig/,'Do not reset corrupt history');
let midnight=null;
for(const [at,w]of [['2026-10-18T23:58:30+02:00',70],['2026-10-18T23:59:00+02:00',70],['2026-10-19T00:00:00+02:00',70],['2026-10-19T00:01:00+02:00',70]])midnight=step(midnight,{at:Date.parse(at),w,binding:'sensor.test'},Date.parse(at));
assert(Math.abs(midnight.days['2026-10-18'].kwh-70*90/3600000)<1e-9);
assert(Math.abs(midnight.days['2026-10-19'].kwh-70*60/3600000)<1e-9);
const restored=step({...midnight,last:null,running:null,pending:null},{at:base+86400000,w:70,binding:'sensor.test'},base+86400000);
assert.equal(restored.total.kwh,midnight.total.kwh,'Restart does not invent energy across downtime');
const flows=require('../flows.json');
assert(flows.find(n=>n.id==='esstpl_climate01').format.includes('aria-label="Compressorregistratie"'));
assert(flows.find(n=>n.id==='essprefs_save').func.includes('result.heatPumpHistory'));
assert(flows.find(n=>n.id==='essprefs_restore').func.includes('saved.heatPumpHistory'));
assert(!flows.find(n=>n.id==='esshp_settings').func.includes('call_service'),'Monitoring never operates the heat pump');
console.log('Heat pump history: hysteresis, debounce, runtime, starts, energy, unknown data, remapping, restart and local midnight passed');
