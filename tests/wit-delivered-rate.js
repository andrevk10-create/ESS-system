const assert=require('assert');
const {witDeliveredRate:rate}=require('../scripts/lib/wit-delivered-rate');
const {witKnownPricePlan:plan}=require('../scripts/lib/wit-known-price-plan');
let p;const now=Date.parse('2026-11-18T00:00:00Z');
for(let i=0;i<5;i++)p=rate(p,now+i*60000,9000,5400,.9,true);
assert.equal(p.planningW,9000,'Do not extrapolate a short start-up dip');
p=rate(p,now+300000,9000,5400,.9,true);
assert.equal(p.planningW,6000,'Account for DC efficiency once, not twice');
assert.equal(rate(p,now+360000,9000,0,.9,false).planningW,6000,'Retain the learned rate between charging slots');
assert.equal(rate(p,now+8000000,9000,0,.9,false).planningW,9000,'Expired delivery is not a permanent restriction');
assert.equal(rate(p,now+360000,8000,5400,.9,true).planningW,8000,'A changed command starts fresh');
let gap=rate(null,now,9000,5400,.9,true);gap=rate(gap,now+300000,9000,5400,.9,true);assert.equal(gap.planningW,9000,'A gap does not count as measured charging');
for(let i=6;i<=17;i++)p=rate(p,now+i*60000,9000,8100,.9,true);
assert.equal(p.planningW,9000,'Delivery recovery shortens the plan again');
const slots=Array.from({length:48},(_,i)=>({start:now+i*900000,end:now+(i+1)*900000,allInPrice:i<32?.1:.5}));
const r={storedKwh:6,capacityKwh:30,efficiency:.9,chargeKw:9,houseKwh:0,solarFactor:0,targetSoc:100};
const normal=plan(slots,now,r,{},{}),slow=plan(slots,now,{...r,chargeKw:6},{},{});
const duration=x=>x.selectedSlots.reduce((sum,s)=>sum+s.end-s.start,0);
assert(duration(slow)>duration(normal),'Sustained lower delivery requires more affordable time');
assert(slow.selectedSlots.every(s=>s.allInPrice===.1),'Do not compensate with expensive slots');
assert(plan(slots,now,{...r,storedKwh:24},{},{}).selectedSlots.reduce((n,s)=>n+s.energyKwh,0)<normal.selectedSlots.reduce((n,s)=>n+s.energyKwh,0),'Updated SOC reduces the remaining energy');
const flows=require('../flows.json'),grid=flows.find(n=>n.id==='esswitgrid_ctrl1').func;
assert(grid.includes('Math.min(planLimitW, gridCommandLimitW, batteryCommandLimitW)'),'The command remains full power');
assert(grid.includes('jointWitKw(flow,states,now,deliveryLimit/1000'),'The joint budget reserves commanded, not reduced delivered power');
console.log('Measured delivery: warmup, gaps, expiry, recovery, replanning, SOC and full-power command passed');
