const assert=require('node:assert/strict');
const {chargingDashboardQuality:quality}=require('../scripts/lib/charging-dashboard-quality');
const {houseLearningStep}=require('../scripts/lib/house-learning');
const now=Date.parse('2026-10-24T23:30:00+02:00');
const daily={schemaVersion:2,recentDays:[{date:'2026-10-23',kwh:40}],updatedAt:new Date(now).toISOString(),sampleValid:false,sampleReason:'Laadmeting ontbreekt',lastValidSampleAt:new Date(now-60000).toISOString(),chargers:[{powerW:null,source:'Meting ontbreekt'}]};
const rows=Array.from({length:24},()=>({seconds:1800,kwh:1}));
const hourly={version:1,days:{'2026-10-23':rows}};
const grid={updatedAt:new Date(now).toISOString(),gridEnergyNeededKwh:8,deadlineHouseKwh:10,expectedSolarChargeKwh:3,currentStoredKwh:12,chargeDeadline:'2026-10-25T12:00:00+01:00',selectedSlots:[{start:'2026-10-24T23:00:00+02:00',end:'2026-10-25T01:00:00+02:00',energyKwh:4},{start:'2026-10-25T06:30:00+01:00',end:'2026-10-25T07:30:00+01:00',energyKwh:2}]};
const original=JSON.stringify({daily,hourly,grid});
const view=quality(daily,hourly,grid,now);
assert.equal(view.learning.active,false);
assert.equal(view.learning.reason,'Laadmeting ontbreekt');
assert.equal(view.learning.completeDays,1);
assert.equal(view.learning.coverage[3].percent,50);
assert.equal(view.learning.coveragePercent,12.5,'Missing calendar days count as uncovered');
assert.equal(view.budget.scheduledKwh,6,'Retain controller snapshot, including the current slot');
assert.equal(view.budget.unplannedKwh,2);
assert.equal(view.budget.periods.length,3,'Midnight and 07:00 split without overlap');
assert.deepEqual(view.budget.periods.map(p=>p.kwh),[2,3,1]);
assert.equal(view.budget.houseKwh,10,'Uses demand until deadline rather than daily average');
assert.equal(JSON.stringify({daily,hourly,grid}),original,'Presentation does not mutate learning or planning');
const stale=quality(daily,hourly,grid,now+180000);
assert.equal(stale.learning.active,false);assert.equal(stale.learning.reason,'Geen recente leercontrole');
assert.equal(stale.budget.scheduledKwh,null);assert.equal(stale.budget.periods.length,0);
assert.equal(quality(null,null,null,now).learning.lastValidAt,null);
assert.equal(quality(null,null,null,now).budget.storedKwh,null);
const dst=quality(null,{version:1,days:{'2026-10-25':Array.from({length:24},(_,i)=>({seconds:i===2?7200:3600,kwh:1}))}},null,Date.parse('2026-10-26T12:00:00+01:00'));
assert.equal(dst.learning.coverage.at(-1).expectedHours,25);
assert.equal(dst.learning.coverage.at(-1).percent,100);
const spring=quality(null,null,null,Date.parse('2026-03-30T12:00:00+02:00'));
assert.equal(spring.learning.coverage.at(-1).expectedHours,23);
const good=houseLearningStep(null,null,{basePowerW:1000,evPowerW:0,chargers:[],reason:'OK'},now,10,'normal');
const paused=houseLearningStep(good,null,{basePowerW:null,evPowerW:null,chargers:[],reason:'Meting ontbreekt'},now+60000,10,'normal');
assert.equal(paused.lastValidSampleAt,good.lastValidSampleAt,'Pause preserves last genuinely accepted sample');
