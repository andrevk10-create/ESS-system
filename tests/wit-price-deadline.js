const assert=require('node:assert/strict');
const {witPriceDeadline}=require('../scripts/lib/wit-price-deadline');
const now=Date.parse('2026-10-10T18:00:00Z');
const slots=prices=>prices.map((allInPrice,i)=>({start:now+i*3600000,end:now+(i+1)*3600000,allInPrice}));
assert.equal(witPriceDeadline(slots([.40,.40,.12,.08,.10,.20,.40,.45]),now),now+6*3600000,'Skip current expensive run and include cheap night');
assert.equal(witPriceDeadline(slots([.10,.08,.15,.40]),now),now+3*3600000);
assert.equal(witPriceDeadline(slots([.20,.20,.20]),now),null,'Flat prices have no expensive period');
const daily = slots([.33,.34,.45,.46,.20,.19,.18,.20,.22,.25,.46,.47]);
const reserve = {storedKwh:23.4,capacityKwh:30,houseKwh:10,efficiency:.9,chargeKw:8};
assert.equal(witPriceDeadline(daily,now,reserve),now+10*3600000,'Bridge morning peak and use cheaper daytime');
assert.equal(witPriceDeadline(daily,now,{...reserve,storedKwh:11}),now+3*3600000,'Keep morning deadline when reserve is insufficient');
assert.equal(witPriceDeadline(daily,now,{...reserve,chargeKw:.1}),now+3*3600000,'Do not postpone without enough recharge capacity');
const {witSolarBeforeDeadline}=require('../scripts/lib/wit-price-deadline');
const solarNow=Date.parse('2026-10-11T18:00:00Z');
const solar={valid:true,forecastDate:'2026-10-12',tomorrowKwh:35,todayRemainingKwh:0};
const sun={'sun.sun':{attributes:{next_rising:'2026-10-12T06:00:00Z',next_setting:'2026-10-12T16:00:00Z'}}};
assert.equal(witSolarBeforeDeadline(solar,sun,solarNow,Date.parse('2026-10-12T04:45:00Z')),0,'No solar before sunrise');
assert.equal(witSolarBeforeDeadline(solar,sun,solarNow,Date.parse('2026-10-12T16:00:00Z')),35,'Solar before evening counts');
assert.equal(witSolarBeforeDeadline({...solar,valid:false},sun,solarNow,Date.parse('2026-10-12T16:00:00Z')),0,'Missing forecast gives no credit');
const flows=require('../flows.json');
const code=flows.find(n=>n.id==='esswitgrid_ctrl1').func;
assert(code.includes("mode === 'auto' ? 100"));
assert(code.includes('slot.end <= expensivePeriodStart'));
assert(!code.includes("if (mode === 'auto' && !forecastValid)"));
console.log('WIT price deadline checks passed');
const {witReserveOpportunity}=require('../scripts/lib/wit-price-deadline');
const evening=Date.parse('2026-10-12T18:30:00Z');
const prices=[...Array(4).fill(.48),...Array(6).fill(.32),...Array(4).fill(.42),...Array(6).fill(.26),...Array(4).fill(.36)];
const tomorrow=prices.map((allInPrice,i)=>({start:evening+i*3600000,end:evening+(i+1)*3600000,allInPrice}));
const actualReserve={storedKwh:26.1,capacityKwh:30,houseKwh:10,efficiency:.9,chargeKw:8,solarFactor:.65};
const forecast={valid:true,forecastDate:'2026-10-13',tomorrowKwh:19.658,todayRemainingKwh:0};
const tomorrowSun={'sun.sun':{attributes:{next_rising:'2026-10-13T06:00:00Z',next_setting:'2026-10-13T16:30:00Z'}}};
const firstDeadline=witPriceDeadline(tomorrow,evening,actualReserve);
assert(firstDeadline<evening+14*3600000,'Reproduces an early morning deadline without a second strong peak');
const wait=witReserveOpportunity(tomorrow,evening,firstDeadline,actualReserve,forecast,tomorrowSun);
assert(wait&&wait.waitUntil>=evening+10*3600000,'Enough reserve waits beyond the morning peak');
assert(wait.projectedReserveKwh>=10);
assert(tomorrow.filter(s=>s.start>=wait.waitUntil&&s.end<=wait.deadline).some(s=>s.allInPrice===.26));
const bridge=witReserveOpportunity(tomorrow,evening,firstDeadline,{...actualReserve,storedKwh:11},forecast,tomorrowSun);
assert(bridge.bridge&&bridge.targetSoc<100,'Low reserve only fills the bridge deficit');
const remaining=11+bridge.bridgeEnergyKwh*.9-10*(bridge.deadline-evening)/86400000;
assert(remaining>=10&&remaining<=11.5,'Bridge leaves the required reserve with at most one 5% rounding buffer');
assert.equal(witReserveOpportunity(tomorrow,evening,firstDeadline,{...actualReserve,chargeKw:.01},{...forecast,valid:false},tomorrowSun),null,'Insufficient daytime refill capacity cannot defer');
assert(witReserveOpportunity(tomorrow,evening,firstDeadline,actualReserve,{...forecast,valid:false},tomorrowSun),'Reliable cheaper hours can be used without solar');
const solarOnly=tomorrow.map(s=>({...s,allInPrice:s.allInPrice===.26?.32:s.allInPrice}));
assert(witReserveOpportunity(solarOnly,evening,firstDeadline,{...actualReserve,storedKwh:30},{...forecast,tomorrowKwh:35},tomorrowSun),'Enough conservative solar can replace grid charging without cheaper prices');
assert.equal(witReserveOpportunity(solarOnly,evening,firstDeadline,{...actualReserve,storedKwh:30},{...forecast,valid:false},tomorrowSun),null,'Unconfirmed solar alone never justifies waiting');
assert(code.includes('slot.start>=reserveWait.waitUntil'),'Deferred plans exclude all overnight slots');
const cheaperNight=tomorrow.map((s,i)=>({...s,allInPrice:i===15?.18:s.allInPrice}));
const cheapestWait=witReserveOpportunity(cheaperNight,evening,firstDeadline,actualReserve,{...forecast,valid:false},tomorrowSun);
assert.equal(cheapestWait.waitUntil,cheaperNight[15].start,'Choose the cheapest reachable refill instead of the first cheaper hour');
const allocationCode=code.slice(code.indexOf('let remainingEnergyKwh ='),code.indexOf('const scheduledSlot ='));
const allocate=new Function('mode','gridEnergyNeededKwh','economicSlots','now','horizonEnd','planLimitW','slots',allocationCode+'return selectedSlots;');
const quarter={start:evening,end:evening+900000,allInPrice:.20,marketPrice:.10};
const shortCharge=allocate('auto',.4,[quarter],evening,evening+86400000,8000,[quarter]);
assert.equal(shortCharge[0].powerKw,8,'Partial final quarter still uses maximum configured power');
assert.equal(shortCharge[0].end-evening,180000,'Only three minutes are required for 0.4 kWh at 8 kW');
assert.equal(shortCharge[0].energyKwh,.4,'Full power must not increase planned energy');
