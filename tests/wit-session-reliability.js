const assert=require('node:assert/strict');
const {witSessionEvidence:validate}=require('../scripts/lib/wit-session-evidence');
const {witManualChargePlan:plan}=require('../scripts/lib/wit-known-price-plan');
const flows=require('../flows.json'),get=id=>flows.find(n=>n.id===id);
const now=Date.parse('2026-10-24T14:34:00Z'),quarter=900000;
const ack={deviceId:'test-wit',configEntryId:'test-entry',remoteEntity:'select.test_remote',authorityEntity:'select.test_authority',at:now,sentAt:now-1000,powerPercent:26};
const evidence={version:1,writeAck:ack,releaseAck:{authority:now-10000},fault:null};
assert.deepEqual(validate(evidence),evidence);
for(const change of [{sentAt:now+1},{configEntryId:''},{powerPercent:-26},{powerPercent:NaN},{remoteEntity:'switch.other'}])assert.equal(validate({...evidence,writeAck:{...ack,...change}}),null);
assert.equal(validate({...evidence,releaseAck:{remote:'123'}}),null);
function fixture(){
 const values={},flow={get:k=>values[k],set:(k,v)=>values[k]=v};
 const run=(id,msg={})=>new Function('flow','node','msg',get(id).func)(flow,{status(){},warn(){},error(){}},msg);
 return {values,flow,run};
}
const warm=fixture();Object.assign(warm.values,{ess_charging_preferences_ready:true,ess_wit_grid_write_ack:ack,ess_wit_release_ack:evidence.releaseAck});
const saved=warm.run('essprefs_save').payload;
assert.deepEqual(JSON.parse(saved).witSessionEvidence,evidence);
assert(!saved.includes('sessionOwned'),'A saved acknowledgement is evidence, never restored ownership');
const cold=fixture();cold.run('essprefs_restore',{payload:saved});
assert.deepEqual(cold.values.ess_wit_grid_write_ack,ack);
assert.deepEqual(cold.values.ess_wit_release_ack,evidence.releaseAck);
assert(!cold.values.ess_wit_grid_charge_status?.sessionOwned);
const released=fixture();released.values.ess_wit_release_ack={remote:now+1000};released.run('essprefs_restore',{payload:saved});
assert.equal(released.values.ess_wit_release_ack.remote,now+1000,'In-memory release cannot be overwritten by older backup');
assert.equal(released.values.ess_wit_release_ack.authority,now-10000,'Both sources of release evidence are preserved');
const newerBackup=fixture();newerBackup.values.ess_wit_release_ack={authority:now-20000};newerBackup.run('essprefs_restore',{payload:saved});
assert.equal(newerBackup.values.ess_wit_release_ack.authority,now-10000,'An older memory timestamp cannot resurrect a released command');
const hard=fixture();Object.assign(hard.values,warm.values,{ess_wit_command_fault:{at:now,reason:'Geen laad- of ontlaadvermogen na herstelpoging',attempts:2,deviceId:'test-wit'}});
const restarted=fixture();restarted.run('essprefs_restore',{payload:hard.run('essprefs_save').payload});
assert.equal(restarted.values.ess_wit_command_fault.reason,hard.values.ess_wit_command_fault.reason,'Restart cannot silently discard a hard fault');
for(const id of ['esswitgrid_transport_dispatch','esswitgrid_transport_reply'])assert(get(id).wires[1].includes('essprefs_save'));
assert.deepEqual(get('esswit_release_ack').wires,[['essprefs_save']]);
const prices=Array.from({length:8},(_,i)=>({start:now+i*quarter,end:now+(i+1)*quarter,allInPrice:i<2?.5:.1}));
const continuous=plan(prices,now,10.33,8);
assert(continuous.length>1,'Manual mode plans beyond the current quarter');
assert.equal(continuous[0].start,now,'Manual mode starts immediately even at an expensive price');
assert(Math.abs(continuous.reduce((s,p)=>s+p.energyKwh,0)-10.33)<1e-9);
assert(Math.abs(continuous.at(-1).end-now-10.33/8*3600000)<1,'Full-power estimate covers the requested energy');
assert(continuous.every((p,i)=>!i||p.start===continuous[i-1].end),'No accidental gaps at quarter boundaries');
assert(plan([],now,5,8).every(s=>s.allInPrice===null),'Unknown prices do not become free electricity');
assert.deepEqual(plan(prices,now,5,0),[]);
assert.equal(plan([],now,1000,1).at(-1).end,now+86400000,'Even an impossible manual request has a bounded forecast horizon');
console.log('WIT session reliability: persisted proof and faults, cold restart, release records, continuous manual charging and unknown prices passed');
