const assert=require('node:assert/strict');
const {houseTimeProfileStep:step,houseTimeProfileForecast:forecast}=require('../scripts/lib/house-time-profile');
const {houseLearningStep}=require('../scripts/lib/house-learning');
const {witKnownPricePlan:plan}=require('../scripts/lib/wit-known-price-plan');
let model=null;
const sample=(at,w)=>{model=step(model,{basePowerW:w},Date.parse(at));};
sample('2026-10-18T23:59:00+02:00',600);sample('2026-10-19T00:01:00+02:00',600);
assert.equal(model.days['2026-10-18'][23].seconds,60);
assert.equal(model.days['2026-10-19'][0].seconds,60);
assert(Math.abs(model.days['2026-10-19'][0].kwh-.01)<1e-9);
const before=model.days['2026-10-19'][0].kwh;
sample('2026-10-19T00:20:00+02:00',600);assert.equal(model.days['2026-10-19'][0].kwh,before,'Do not bridge missing samples');
sample('2026-10-19T00:21:00+02:00',null);sample('2026-10-19T00:22:00+02:00',2000);
assert.equal(model.days['2026-10-19'][0].kwh,before,'Invalid EV-free sample clears the integration anchor');
const copy=JSON.parse(JSON.stringify({...model,last:null}));
assert.equal(step(copy,{basePowerW:1000},Date.parse('2026-10-19T00:23:00+02:00')).days['2026-10-19'][0].kwh,before,'Restart does not invent history');
let dst=null;
for(const at of ['2026-10-25T00:59:00Z','2026-10-25T01:01:00Z'])dst=step(dst,{basePowerW:1000},Date.parse(at));
assert.equal(dst.days['2026-10-25'][2].seconds,120,'Repeated DST hour stays in its actual local clock bucket');
const now=Date.parse('2026-10-18T18:00:00Z'),hour=3600000;
const days=Object.fromEntries(['2026-10-15','2026-10-16','2026-10-17'].map(day=>[day,Array.from({length:24},(_,h)=>({kwh:h<8?.4:2,seconds:3600}))]));
const known={version:1,days,last:null};
const profile=forecast(known,now,now+30*hour,36);
assert.equal(profile.days,3);
assert(Math.abs(profile.segments.find(s=>new Date(s.start).toISOString()==='2026-10-19T00:00:00.000Z').kwhPerHour-.4)<1e-9,'Night uses measured night demand instead of the daily average');
assert.equal(profile.learnedHours,profile.hours);
const grouped={version:1,days:Object.fromEntries(['2026-10-13','2026-10-14','2026-10-15','2026-10-03','2026-10-10','2026-10-17'].map(day=>[day,Array.from({length:24},()=>({kwh:['03','10','17'].includes(day.slice(-2))?2:.4,seconds:3600}))]))};
const groupedForecast=forecast(grouped,now,now+30*hour,36);
assert(Math.abs(groupedForecast.segments.find(s=>s.start===Date.parse('2026-10-19T00:00:00Z')).kwhPerHour-.4)<1e-9,'Use a weekday profile when at least three matching weekdays were measured');
const partial=JSON.parse(JSON.stringify(known));for(const rows of Object.values(partial.days))rows[2]={kwh:0,seconds:0};
const missing=forecast(partial,now,now+30*hour,36);
assert(missing.segments.some(s=>!s.learned&&s.kwhPerHour===1.5),'Unknown hours remain clearly labelled daily-average fallbacks');
const prices=Array.from({length:120},(_,i)=>{const h=i/4;return {start:now+i*hour/4,end:now+(i+1)*hour/4,allInPrice:h<4?.45:h<12?.34:h<17?.48:h<21?.26:h<25?.52:.38};});
const r={storedKwh:18,capacityKwh:30,houseKwh:36,efficiency:.9,chargeKw:8,targetSoc:100,solarFactor:.65};
const flat=plan(prices,now,r,{valid:false},{}),timed=plan(prices,now,{...r,hourlyProfile:profile},{valid:false},{});
const overnight=p=>p.selectedSlots.filter(s=>s.end<=now+12*hour).reduce((sum,s)=>sum+s.energyKwh,0);
assert(overnight(timed)<overnight(flat),'A quiet measured night reduces night charging without hiding daytime peaks');
assert(timed.projectedSoc>=99.99&&timed.minimumSoc>=20-.001,'Refill goal and separate reserve remain covered');
const old=JSON.parse(JSON.stringify(known));old.days['2026-09-01']=old.days['2026-10-15'];
const aged=step(old,{basePowerW:600},now);assert(!aged.days['2026-09-01'],'Expired hourly data is pruned');
const daily={schemaVersion:2,currentDate:'2026-10-18',recentDays:[{date:'2026-09-25',kwh:10},{date:'2026-10-16',kwh:10},{date:'2026-10-17',kwh:40}],currentValueKwh:0,coverageHours:0};
const averaged=houseLearningStep(daily,null,{basePowerW:null,reason:'test'},now,10,'test');
assert.equal(averaged.forecastKwh,20,'Use the actual arithmetic mean including days older than a week');
assert.equal(averaged.recentDays.length,3);
const {witLearnedHouse}=require('../scripts/lib/wit-price-deadline');
assert.equal(witLearnedHouse({...averaged,updatedAt:new Date(now).toISOString()},now,10).kwh,20,'WIT uses the same 30-day average');
const flows=require('../flows.json');
assert(flows.find(n=>n.id==='esswithist_prep1').func.includes('houseTimeProfileStep('));
assert(flows.find(n=>n.id==='essprefs_save').func.includes('result.houseTimeProfile='));
assert(flows.find(n=>n.id==='essprefs_restore').func.includes('saved.houseTimeProfile'));
assert(!flows.find(n=>n.id==='esswitgrid_ctrl1').func.includes('r.houseKwh*1.25/86400000'),'No blanket 25% multiplier on day and night demand');
console.log('Household time profile: 30-day means, clock hours, EV-free sample gating, gaps, restart, DST, fallback coverage and cheaper reserve bridge passed');
